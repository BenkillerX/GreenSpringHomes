import {Router} from 'express';
import { getAllServiceProviders, getServiceProviderById, getServiceProviderProfile, updateServiceProviderProfile } from './service-providers.controllers.js';
import { authenticateToken } from '../../middleware/auth.middleware.js';
import { authorizeRoles } from '../../middleware/role.middleware.js';
import { upload } from '../../middleware/upload.middleware.js';
const serviceProviderRoutes = Router();
serviceProviderRoutes.get( "/", authenticateToken, authorizeRoles("tenant","propertyOwner", "serviceProvider","admin"), getAllServiceProviders );
serviceProviderRoutes.get( "/profile", authenticateToken, getServiceProviderProfile );
serviceProviderRoutes.put( "/profile", authenticateToken, authorizeRoles("serviceProvider"), upload.single("image"), updateServiceProviderProfile );
serviceProviderRoutes.get( "/:id", authenticateToken, authorizeRoles("tenant","propertyOwner", "serviceProvider","admin"), getServiceProviderById );
export default serviceProviderRoutes;